CREATE TABLE IF NOT EXISTS instruments (
    symbol VARCHAR(16) PRIMARY KEY,
    name VARCHAR(128) NOT NULL,
    exchange VARCHAR(32) NOT NULL,
    asset_class VARCHAR(32) NOT NULL,
    quote_currency VARCHAR(8) NOT NULL,
    tick_size DECIMAL(18, 8) NOT NULL,
    timezone VARCHAR(64) NOT NULL,
    delayed_feed BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS bars (
    symbol VARCHAR(16) NOT NULL,
    timeframe VARCHAR(8) NOT NULL,
    bar_index BIGINT NOT NULL,
    open_time TIMESTAMP WITH TIME ZONE NOT NULL,
    close_time TIMESTAMP WITH TIME ZONE NOT NULL,
    open_price DECIMAL(18, 8) NOT NULL,
    high_price DECIMAL(18, 8) NOT NULL,
    low_price DECIMAL(18, 8) NOT NULL,
    close_price DECIMAL(18, 8) NOT NULL,
    volume DECIMAL(24, 4) NOT NULL,
    PRIMARY KEY (symbol, timeframe, bar_index)
);

CREATE TABLE IF NOT EXISTS signals (
    signal_id VARCHAR(64) PRIMARY KEY,
    symbol VARCHAR(16) NOT NULL,
    timeframe VARCHAR(8) NOT NULL,
    direction VARCHAR(8) NOT NULL,
    state VARCHAR(24) NOT NULL,
    entry_price DECIMAL(18, 8) NOT NULL,
    stop_loss DECIMAL(18, 8) NOT NULL,
    tp1_price DECIMAL(18, 8) NOT NULL,
    tp2_price DECIMAL(18, 8) NOT NULL,
    tp3_price DECIMAL(18, 8) NOT NULL,
    confidence INT NOT NULL,
    confluence_score DOUBLE PRECISION NOT NULL,
    regime VARCHAR(32) NOT NULL,
    strategy_id VARCHAR(64) NOT NULL,
    strategy_version INT NOT NULL,
    opened_at_bar BIGINT NOT NULL,
    opened_at TIMESTAMP WITH TIME ZONE NOT NULL,
    closed_at TIMESTAMP WITH TIME ZONE,
    explanation TEXT
);

CREATE TABLE IF NOT EXISTS strategy_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy_id VARCHAR(64) NOT NULL,
    version INT NOT NULL,
    actor VARCHAR(128) NOT NULL,
    action VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

